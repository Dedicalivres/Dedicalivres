import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context = {};
vm.runInNewContext(fs.readFileSync(new URL('../local-preferences.js', import.meta.url), 'utf8'), context);
const create = context.DEDICALIVRES_LOCAL.createStore;
const memory = new Map([['dedicalivres_favorites', '["old"]']]);
const storage = { getItem: k => memory.get(k), setItem: (k,v) => memory.set(k,v) };
let store = create(storage);
const event = { id: 1, country_code: 'FR', region: 'Bretagne', type: 'Salon' };
assert.equal(store.add({ country: 'FR', region: 'Bretagne', type: 'Salon' }, [event]), true);
assert.equal(store.unseen([event]).length, 0, 'existing catalog is baseline');
const next = { ...event, id: 2 };
assert.equal(store.unseen([event, next, { ...next, id: 3, country_code: 'BE' }]).length, 1);
store = create(storage);
assert.equal(store.unseen([next]).length, 1, 'unread survives another visit');
assert.equal(store.acknowledge([next]), true);
assert.equal(create(storage).unseen([next]).length, 0);
assert.equal(memory.get('dedicalivres_favorites'), '["old"]', 'legacy favorites untouched');
store.remove(0);
assert.equal(store.unseen([next]).length, 0);
memory.set('dedicalivres_local_preferences_v1', '{"version":1,"rules":[null]}');
assert.equal(store.read().rules.length, 0, 'malformed storage is safe');
assert.equal(create({ getItem() { throw Error(); }, setItem() { throw Error(); } }).add({}, []), false);
console.log('PASS local preferences: baseline, matching, reload, acknowledgement, removal, corrupt/blocked storage, legacy preservation');
